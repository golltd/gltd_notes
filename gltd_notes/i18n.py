SUPPORTED = ("auto", "pt", "en", "es", "de", "zh", "ja")

_LANG_LABELS = {
    "auto": "language_auto",
    "pt": "Português",
    "en": "English",
    "es": "Español",
    "de": "Deutsch",
    "zh": "中文",
    "ja": "日本語",
}


def detect_system_lang() -> str:
    try:
        loc = locale.getdefaultlocale()[0] or ""
    except Exception:
        loc = ""
    loc = loc.lower().replace("_", "-")
    if loc.startswith("pt"):
        return "pt"
    if loc.startswith("es"):
        return "es"
    if loc.startswith("de"):
        return "de"
    if loc.startswith("ja"):
        return "ja"
    if loc.startswith("zh"):
        return "zh"
    if loc.startswith("en"):
        return "en"
    return "pt"


class I18n:
    def __init__(self, language: str = "auto"):
        self.set_language(language)

    def set_language(self, language: str) -> None:
        code = (language or "auto").lower()
        if code not in SUPPORTED:
            code = "auto"
        self.preference = code
        self.lang = detect_system_lang() if code == "auto" else code
        if self.lang not in _TRANSLATIONS:
            self.lang = "en"

    def t(self, key: str, **kwargs) -> str:
        table = _TRANSLATIONS.get(self.lang) or _TRANSLATIONS["en"]
        text = table.get(key) or _TRANSLATIONS["en"].get(key) or key
        if kwargs:
            try:
                return text.format(**kwargs)
            except Exception:
                return text
        return text

    def language_choices(self) -> list:
        out = []
        for code in SUPPORTED:
            if code == "auto":
                out.append((code, f"{self.t('language_auto')} ({detect_system_lang()})"))
            else:
                out.append((code, _LANG_LABELS.get(code, code)))
        return out


_i18n: Optional[I18n] = None


def get_i18n(language: Optional[str] = None) -> I18n:
    global _i18n
    if _i18n is None:
        _i18n = I18n(language or "auto")
    elif language is not None:
        _i18n.set_language(language)
    return _i18n


def t(key: str, **kwargs) -> str:
    return get_i18n().t(key, **kwargs)
